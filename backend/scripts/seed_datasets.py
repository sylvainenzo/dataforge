"""Idempotent seed for the dataset library. Both datasets here are
genuinely synthetic — generated by this script with a fixed random seed,
not sourced from (or claiming to be) any real external dataset. That's a
deliberate choice, not a shortcut: fabricating a source/license for a
dataset that only *looks* real would violate the exact rule the Dataset
model's own docstring states (never fabricate dataset ownership or
licensing). The source/license fields say exactly this, honestly.

Writes real CSV files to storage/datasets/, profiles them with the same
profile_dataframe() the real upload path uses, and registers them —
these are functional, downloadable, profileable datasets, not just
metadata rows.

Run: python3 scripts/seed_datasets.py
"""

import asyncio
import random
import uuid
from pathlib import Path

import pandas as pd
from sqlalchemy import select

from app.core.config import settings
from app.core.db import AsyncSessionLocal
from app.models.base import DifficultyLevel
from app.models.datasets import Dataset, DatasetFormat, DatasetVersion, ProfilingStatus
from app.services.dataset_profiling import profile_dataframe

SYNTHETIC_SOURCE = "DataForge (synthetic)"
SYNTHETIC_LICENSE = "Generated by DataForge for learning purposes — not real-world data, freely reusable (CC0-equivalent)."


def build_income_survey() -> pd.DataFrame:
    """Deliberately messy, matching the Income Survey EDA project's brief
    exactly: missing values in age and income, plus one clear outlier."""

    rng = random.Random(42)
    regions = ["North", "South", "East", "West"]
    education_levels = ["High School", "Bachelor's", "Master's", "PhD"]

    rows = []
    for i in range(40):
        age = rng.randint(22, 65)
        base_income = 28000 + (age - 22) * 900 + rng.randint(-4000, 4000)
        rows.append(
            {
                "respondent_id": i + 1,
                "age": age,
                "education": rng.choice(education_levels),
                "region": rng.choice(regions),
                "employment_status": rng.choice(["Employed", "Employed", "Employed", "Self-employed", "Unemployed"]),
                "income": max(0, base_income),
            }
        )

    # A handful of genuine missing values, and one clear data-entry-error
    # outlier — this is what makes it a real EDA exercise, not a clean toy.
    for idx in [3, 17, 29]:
        rows[idx]["age"] = None
    for idx in [8, 22]:
        rows[idx]["income"] = None
    rows[12]["income"] = 985000  # the outlier the project brief refers to

    return pd.DataFrame(rows)


def build_retail_sales() -> pd.DataFrame:
    """A general-purpose synthetic sales dataset for groupby/aggregation
    practice — daily sales across a few product categories and regions."""

    rng = random.Random(7)
    categories = ["Electronics", "Home & Garden", "Apparel", "Groceries", "Sporting Goods"]
    regions = ["North", "South", "East", "West"]
    base_price = {"Electronics": 220, "Home & Garden": 45, "Apparel": 35, "Groceries": 12, "Sporting Goods": 60}

    rows = []
    dates = pd.date_range("2026-01-01", periods=60, freq="D")
    for date in dates:
        for _ in range(rng.randint(2, 5)):
            category = rng.choice(categories)
            units = rng.randint(1, 25)
            price = base_price[category] * rng.uniform(0.85, 1.15)
            rows.append(
                {
                    "date": date.date().isoformat(),
                    "category": category,
                    "region": rng.choice(regions),
                    "units_sold": units,
                    "revenue": round(units * price, 2),
                }
            )

    return pd.DataFrame(rows)


DATASETS = [
    {
        "name": "Income Survey Sample",
        "slug": "income-survey-sample",
        "description": "A small, deliberately messy synthetic income survey — missing values and one clear outlier, built to pair with the Income Survey EDA project.",
        "domain": "Social Science",
        "difficulty": DifficultyLevel.BEGINNER,
        "builder": build_income_survey,
    },
    {
        "name": "Retail Sales Sample",
        "slug": "retail-sales-sample",
        "description": "60 days of synthetic daily retail sales across 5 product categories and 4 regions — good for groupby, aggregation, and time-based practice.",
        "domain": "Retail",
        "difficulty": DifficultyLevel.BEGINNER,
        "builder": build_retail_sales,
    },
]


async def seed() -> None:
    async with AsyncSessionLocal() as db:
        storage_dir = Path(settings.dataset_storage_path)
        storage_dir.mkdir(parents=True, exist_ok=True)

        added = 0
        for spec in DATASETS:
            existing = await db.execute(select(Dataset).where(Dataset.slug == spec["slug"]))
            if existing.scalar_one_or_none() is not None:
                continue

            df = spec["builder"]()
            storage_key = f"{uuid.uuid4()}_{spec['slug']}.csv"
            file_path = storage_dir / storage_key
            df.to_csv(file_path, index=False)
            file_size = file_path.stat().st_size

            profiling_result = profile_dataframe(df)

            dataset = Dataset(
                name=spec["name"],
                slug=spec["slug"],
                description=spec["description"],
                source=SYNTHETIC_SOURCE,
                source_url="internal://synthetic",
                license=SYNTHETIC_LICENSE,
                domain=spec["domain"],
                difficulty=spec["difficulty"],
                format=DatasetFormat.CSV,
            )
            db.add(dataset)
            await db.flush()

            db.add(
                DatasetVersion(
                    dataset_id=dataset.id,
                    version_number=1,
                    storage_key=storage_key,
                    row_count=profiling_result["row_count"],
                    column_count=profiling_result["column_count"],
                    file_size_bytes=file_size,
                    profiling_status=ProfilingStatus.COMPLETE,
                    profiling_result=profiling_result,
                )
            )
            added += 1

        await db.commit()
        print(f"Seed complete: {added} datasets added (of {len(DATASETS)}).")


if __name__ == "__main__":
    asyncio.run(seed())
