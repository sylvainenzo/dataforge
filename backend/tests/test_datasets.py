async def test_upload_real_csv_parses_and_profiles(client):
    await _register_and_login(client)
    resp = await client.post(
        "/api/v1/datasets/upload",
        files={"file": ("my_data.csv", _csv_bytes(5), "text/csv")},
        data={"name": "My Upload", "description": "A test upload."},
    )
    assert resp.status_code == 201
    body = resp.json()
    assert body["name"] == "My Upload"
    assert body["format"] == "csv"

    detail_resp = await client.get(f"/api/v1/datasets/{body['slug']}")
    assert detail_resp.status_code == 200
    version = detail_resp.json()["latest_version"]
    assert version["row_count"] == 5
    assert version["column_count"] == 3
    assert version["profiling_status"] == "complete"


async def test_upload_rejects_unsupported_file_type(client):
    await _register_and_login(client)
    resp = await client.post(
        "/api/v1/datasets/upload",
        files={"file": ("notes.txt", b"just some text", "text/plain")},
        data={"name": "Bad upload", "description": ""},
    )
    assert resp.status_code == 400
    assert "Unsupported file type" in resp.json()["detail"]


async def test_upload_rejects_oversized_file(client, monkeypatch):
    from app.api.v1 import datasets as datasets_route

    monkeypatch.setattr(datasets_route.settings, "dataset_max_upload_mb", 0)
    await _register_and_login(client)
    resp = await client.post(
        "/api/v1/datasets/upload",
        files={"file": ("my_data.csv", _csv_bytes(5), "text/csv")},
        data={"name": "Too big", "description": ""},
    )
    assert resp.status_code == 413


async def test_upload_rate_limit_kicks_in_after_five_per_minute(client):
    await _register_and_login(client)
    for i in range(5):
        resp = await client.post(
            "/api/v1/datasets/upload",
            files={"file": (f"file{i}.csv", _csv_bytes(2), "text/csv")},
            data={"name": f"Upload {i}", "description": ""},
        )
        assert resp.status_code == 201

    sixth = await client.post(
        "/api/v1/datasets/upload",
        files={"file": ("file6.csv", _csv_bytes(2), "text/csv")},
        data={"name": "Upload 6", "description": ""},
    )
    assert sixth.status_code == 429
