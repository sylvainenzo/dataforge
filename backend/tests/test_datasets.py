async def _register_and_login(client, email="dataset-user@test.dev"):
    await client.post(
        "/api/v1/auth/register", json={"email": email, "password": "correcthorsebattery", "display_name": "U"}
    )


def _csv_bytes(rows: int = 3) -> bytes:
    lines = ["a,b,c"] + [f"{i},{i * 2},cat{i}" for i in range(rows)]
    return "\n".join(lines).encode()


async def test_list_datasets_is_public(client, seeded_dataset):
    resp = await client.get("/api/v1/datasets")
    assert resp.status_code == 200
    assert any(d["slug"] == seeded_dataset for d in resp.json())


async def test_get_dataset_detail_includes_latest_version(client, seeded_dataset):
    resp = await client.get(f"/api/v1/datasets/{seeded_dataset}")
    assert resp.status_code == 200
    body = resp.json()
    assert body["name"] == "Seeded Test Dataset"
    assert body["latest_version"]["row_count"] == 10
    assert body["latest_version"]["column_count"] == 3


